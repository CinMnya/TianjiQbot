def _cb_arg_to_dt(arg: str) -> datetime:
    """出生信息 → datetime；空则用现在。"""
    text = (arg or "").strip()
    if not text:
        return datetime.now()
    b = parse_birth_info(text)
    return datetime(b.year, b.month, b.day, b.hour, b.minute)


def chenggu(arg: str = "") -> str:
    """称骨算命。参数: [出生信息]，缺省用当前时刻。"""
    dt = _cb_arg_to_dt(arg)
    solar = Solar.fromYmdHms(dt.year, dt.month, dt.day, dt.hour, dt.minute, 0)
    lunar = solar.getLunar()
    y_gz = lunar.getYearInGanZhi()
    m = abs(lunar.getMonth())
    d = lunar.getDay()
    h = ZHI[(dt.hour + 1) // 2 % 12]

    try:
        wy = _CB_YEAR[y_gz]
        wm = _CB_MONTH[m - 1]
        wd = _CB_DAY[d - 1]
        wh = _CB_HOUR[h]
    except KeyError as exc:
        raise ValueError(f"称骨数据缺失：{exc}（请检查日期是否超范围）")

    total = wy + wm + wd + wh
    liang, qian = divmod(total, 10)
    if qian == 0:
        qian = 10
        liang -= 1
    desc = _CB_COMMENT.get(total, "骨重超出常规区间，建议核对日期。")

    lines = [
        "【称骨算命】",
        f"生辰：{y_gz}年 农历{lunar.getMonthInChinese()}月{lunar.getDayInChinese()} {h}时",
        f"骨重明细：年{wy / 10:.1f}两 + 月{wm / 10:.1f}两 + 日{wd / 10:.1f}两 + 时{wh / 10:.1f}两",
        f"总骨重：{liang}两{qian}钱",
        f"评注：{desc}",
        "提示：称骨以骨重论命，越重越贵是通说；歌诀各版本略有出入，本表取通行数据、白话释义。",
        _SC_NOTE,
    ]
    return "\n".join(lines)
