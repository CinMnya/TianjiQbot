# 卦名 -> 八宫信息缓存
_GUA_INDEX = {}
for _palace, _names in PALACE_ORDER.items():
    for _i, _name in enumerate(_names):
        _GUA_INDEX[_name] = {
            "palace": _palace,
            "palace_wx": PALACE_WX[_palace],
            "shi": PALACE_SHI[_i],
            "ying": PALACE_SHI[_i] + 3 if PALACE_SHI[_i] <= 3 else PALACE_SHI[_i] - 3,
            "rank": _i,
        }

# 上下卦 -> 卦名
_BY_TRIGRAM = {}
for _name, (_up, _low, _m) in GUA64.items():
    _BY_TRIGRAM[(_up, _low)] = _name


def gua_by_trigrams(upper: str, lower: str) -> str:
    """上卦 + 下卦 -> 卦名。"""
    return _BY_TRIGRAM[(upper, lower)]


def gua_info(name: str) -> dict:
    """返回卦的完整信息: 上下卦、卦意、八宫、世应、五行。"""
    up, low, meaning = GUA64[name]
    info = dict(_GUA_INDEX.get(name, {}))
    info.update({"name": name, "upper": up, "lower": low, "meaning": meaning})
    return info


def najia(name: str) -> list:
    """返回六爻纳甲: [(位置, 干支, 单爻阴阳), ...] 自初爻至上爻。"""
    up, low, _ = GUA64[name]
    out = []
    for i in range(6):
        trigram = low if i < 3 else up
        zhi = NAJIA_ZHI[trigram][i]
        gan = NAJIA_GAN[trigram]
        if i >= 3 and trigram in NAJIA_GAN_OUT:
            gan = NAJIA_GAN_OUT[trigram]
        yang = BAGUA_YAO[trigram][i % 3]
        out.append((i + 1, gan + zhi, yang))
    return out


def gua_from_yao(yaos: list) -> str:
    """六爻阴阳列表(自初爻起, 1阳0阴) -> 卦名。"""
    low = YAO_TO_BAGUA[tuple(yaos[0:3])]
    up = YAO_TO_BAGUA[tuple(yaos[3:6])]
    return gua_by_trigrams(up, low)


def gua_symbol(name: str) -> str:
    """卦的上下卦文字描述，如 '上坎下震'。"""
    up, low, _ = GUA64[name]
    return f"上{up}下{low}"


def gua_nature(name: str) -> str:
    """象意描述，如 '水在雷上'。"""
    up, low, _ = GUA64[name]
    return f"{BAGUA[up]['nature']}在{BAGUA[low]['nature']}上"
